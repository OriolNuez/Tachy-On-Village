import { _electron as electron } from 'playwright';
import { build } from 'vite';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';

const root = resolve('.');
const temporary = await mkdtemp(join(tmpdir(), 'tachyon-outlook-ui-'));
const cadence = join(temporary, 'Tachyon', 'Cadences', 'Synthetic Test');
for (const group of ['Accounts', 'Contacts', 'Storage']) await mkdir(join(cadence, group), { recursive: true });
const contactFile = join(cadence, 'Contacts', 'Synthetic Test_contacts.csv');
const original = 'Name,Company,Email,Email Verified\nAlex Example,Example Labs,alex@example.test,Yes\n';
await writeFile(contactFile, original);
const messaging = join(temporary, 'Tachyon', 'messaging');
await mkdir(messaging);
const template = 'Subject: Synthetic hello {company}\n\nHi {first_name}, this is an invented test message.';
await writeFile(join(messaging, 'synthetic.txt'), template);
const pythonSource = await readFile(join(root, 'backend/scripts/outlook_drafter.py'), 'utf8');
let desktop;
try {
  await build({ configFile: false, logLevel: 'error', build: { ssr: true, outDir: join(temporary, 'harness'), rollupOptions: { input: join(root, 'tests/fixtures/jobs-desktop-main.ts'), external: ['electron'], output: { entryFileNames: 'index.mjs' } } } });
  const env = { ...process.env, TACHYON_TEST_REPO: root, TACHYON_DATA_ROOT: join(temporary, 'Tachyon') };
  delete env.ELECTRON_RUN_AS_NODE;
  const launch = () => electron.launch({ args: [join(temporary, 'harness/index.mjs'), `--user-data-dir=${join(temporary, 'profile')}`], env, chromiumSandbox: true });
  desktop = await launch();
  let page = await desktop.firstWindow(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const openCadence = async () => {
    await page.getByRole('button', { name: 'Existing Cadences' }).click();
    await page.getByRole('button', { name: /CADENCE 01 Synthetic Test/ }).click();
    await page.getByRole('button', { name: '+ Draft Emails', exact: true }).click();
    await page.getByRole('dialog', { name: 'Prepare Outlook Drafts' }).waitFor();
  };
  await openCadence();
  await page.getByText('1 selected of 1 eligible contacts.', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Launch Outlook' }).isEnabled(), false);
  assert.equal((await page.evaluate(() => window.villageDesktop.jobs.current())).data, null);
  await page.getByLabel('I reviewed the recipients', { exact: false }).check();
  await page.getByLabel('Text files in messaging/').selectOption('synthetic.txt');
  await page.getByRole('button', { name: 'Import .txt', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Imported synthetic.txt' }).waitFor();
  assert.equal(await page.getByLabel('Subject', { exact: true }).inputValue(), 'Synthetic hello {company}');
  assert.equal(await page.getByLabel('Message body', { exact: true }).inputValue(), 'Hi {first_name}, this is an invented test message.');
  assert.equal(await readFile(join(messaging, 'synthetic.txt'), 'utf8'), template);
  assert.equal(await page.getByRole('button', { name: 'Launch Outlook' }).isEnabled(), false);
  await page.getByLabel('Cadence step (1–100)', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Update preview' }).click();
  await page.getByText('1 selected of 1 eligible contacts.', { exact: false }).waitFor();
  await page.getByLabel('I reviewed the recipients', { exact: false }).check();
  await page.getByRole('button', { name: 'Launch Outlook', exact: true }).click();
  await page.getByRole('button', { name: 'Start Drafting', exact: true }).waitFor();
  assert.equal(await readFile(contactFile, 'utf8'), original);
  const lock = await page.evaluate(() => window.villageDesktop.jobs.startCognism('Synthetic Test'));
  assert.equal(lock.ok, false);
  await page.getByRole('button', { name: 'Start Drafting', exact: true }).click();
  await page.getByRole('button', { name: 'Close Browser', exact: true }).waitFor();
  const current = (await page.evaluate(() => window.villageDesktop.jobs.current())).data;
  assert.equal(current.outlook.subjectVisible, 1); assert.equal(current.outlook.uncertain, 0);
  await page.getByRole('button', { name: 'Close Browser', exact: true }).click();
  await page.locator('.job-status span').filter({ hasText: /^completed$/ }).waitFor();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  const history = page.getByRole('region', { name: 'Draft history', exact: true });
  await history.getByText('Subject found in Drafts — review required', { exact: true }).waitFor();
  await history.getByLabel('Email subject', { exact: true }).selectOption('Synthetic hello Example Labs');
  await history.getByLabel('Cadence step', { exact: true }).selectOption('2');
  await history.getByRole('cell', { name: 'Step 2', exact: true }).waitFor();
  await history.getByLabel('Cadence step', { exact: true }).selectOption('unassigned');
  await history.getByText('No drafts match these filters', { exact: true }).waitFor();
  await history.getByLabel('Cadence step', { exact: true }).selectOption('');
  assert.equal(await page.getByRole('columnheader', { name: 'Sent', exact: true }).count(), 0);
  const replied = history.getByRole('checkbox', { name: /Replied: alex@example.test/ });
  assert.equal(await replied.isEnabled(), false);
  await history.getByRole('button', { name: 'Edit replies', exact: true }).click();
  await replied.click();
  await history.getByRole('status').filter({ hasText: /^1 replied$/ }).waitFor();
  const repliedSection = page.getByRole('region', { name: 'Replied emails', exact: true });
  await repliedSection.getByRole('cell', { name: 'Synthetic hello Example Labs', exact: true }).waitFor();
  await replied.click();
  await repliedSection.getByText('No emails marked as replied yet', { exact: true }).waitFor();
  await replied.click();
  await repliedSection.getByRole('cell', { name: 'Synthetic hello Example Labs', exact: true }).waitFor();

  await page.waitForFunction(async () => {
    const result = await window.villageDesktop.cadences.read('Synthetic Test');
    return result.ok && Object.values(result.data.replies ?? {}).includes(true);
  });


  await page.getByRole('button', { name: '+ Draft Emails', exact: true }).click();
  await page.getByText('0 selected of 0 eligible contacts.', { exact: false }).waitFor();
  await page.getByText('Durable attempt history', { exact: false }).click();
  await page.getByText('subject visible review required', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Launch Outlook' }).isEnabled(), false);
  assert.equal(await readFile(contactFile, 'utf8'), original);
  assert.deepEqual(errors, []);
  await desktop.close(); desktop = await launch();
  page = await desktop.firstWindow(); page.setDefaultTimeout(15000);
  await openCadence();
  await page.getByText('0 selected of 0 eligible contacts.', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Launch Outlook' }).isEnabled(), false);
  assert.equal(await page.getByRole('checkbox', { name: /Replied: alex@example.test/ }).isChecked(), true);
  await page.getByRole('region', { name: 'Replied emails', exact: true }).getByRole('cell', { name: 'Synthetic hello Example Labs', exact: true }).waitFor();
  assert.equal(await readFile(join(root, 'backend/scripts/outlook_drafter.py'), 'utf8'), pythonSource);
  console.log('SYNTHETIC ONLY: Outlook exact preview/consent, explicit ready/close, real adapter counters, profile exclusion, durable attempt history and restart retry blocking passed. No live Outlook or Send action.');
} finally {
  if (desktop) await desktop.close();
  await rm(temporary, { recursive: true, force: true });
}
